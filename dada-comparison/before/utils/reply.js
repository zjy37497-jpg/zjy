const FIXED_REPLIES = [
  { test: /^菜园$/, body: '我想你，菜园！[[sticker:cute]]' },
  { test: /^小九$/, body: '我想你小孙孙！嘻嘻[[sticker:cute]]' },
  {
    test: /^(啤啤|皮皮)$/i,
    body: '萌萌我爱你！'
  },
  {
    test: /^周丽琴$/,
    body: '妈咪我爱你！'
  }
];

function matched(rule, text) {
  return typeof rule.test === 'function' ? rule.test(text) : rule.test.test(text);
}

function fixedReply(text) {
  const input = String(text || '').trim();
  const rule = FIXED_REPLIES.find(item => item.test.test(input));
  return rule ? rule.body : '';
}

function reply(text) {
  const input = String(text || '').trim();
  const fixed = fixedReply(input);
  if (fixed) return fixed;
  for (const rule of RULES) {
    if (matched(rule, input)) return rule.body;
  }
  // 兜底：给出通用回应，不显示错误或“未识别”
  return '收到。\n运动的基本原则：循序渐进，量力而行，出现不适及时停止。\n可以输入具体问题，例如：“只有20分钟，在家怎么练”“想减脂，三餐怎么搭配”。';
}

// 高风险症状：无论哪种模式都先走本地规则，不交给模型
function emergency(text) {
  const rule = RULES[0];
  return rule.test.test(String(text || '')) ? rule.body : null;
}

